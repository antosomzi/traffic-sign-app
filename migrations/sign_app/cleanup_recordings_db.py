def main() -> None:
    parser = argparse.ArgumentParser(
        description="Delete recordings from DB (dry-run by default)",
    )
    parser.add_argument(
        "--apply",
        action="store_true",
        help="Apply deletions (default is dry-run)",
    )
    args = parser.parse_args()

    dry_run = not args.apply

    print("=" * 60)
    print("DB cleanup: recordings")
    print("=" * 60)
    print(f"Dry run: {dry_run}")
    print(f"Total candidate recordings: {len(RECORDING_IDS)}")

    existing = []
    missing = []

    for recording_id in RECORDING_IDS:
        if Recording.exists(recording_id):
            existing.append(recording_id)
        else:
            missing.append(recording_id)

    print(f"Existing in DB: {len(existing)}")
    print(f"Missing in DB: {len(missing)}")

    if existing:
        print("\nRecordings to delete:")
        for recording_id in existing:
            print(f"- {recording_id}")

    if not dry_run and existing:
        for recording_id in existing:
            Recording.delete(recording_id)
        print("✅ DB deletions applied")


if __name__ == "__main__":
    main()
